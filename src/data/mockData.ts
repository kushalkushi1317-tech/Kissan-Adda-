export function getUniqueStates(records: MarketPriceRecord[]): string[] {
  return Array.from(new Set(records.map(r => r.state))).sort();
}

export function getDistrictsForState(records: MarketPriceRecord[], state: string): string[] {
  return Array.from(
    new Set(
      records
        .filter(r => !state || r.state.toLowerCase() === state.toLowerCase())
        .map(r => r.district)
    )
  ).sort();
}

export function getMandisForDistrict(records: MarketPriceRecord[], district: string): string[] {
  return Array.from(
    new Set(
      records
        .filter(r => !district || r.district.toLowerCase() === district.toLowerCase())
        .map(r => r.mandiName)
    )
  ).sort();
}
